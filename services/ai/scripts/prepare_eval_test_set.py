#!/usr/bin/env python3
"""Freeze the held-out evaluation test set for the SentinelPH eval harness.

Reads the processed train/test split's test file (text, label[int 0/1/2])
and writes a frozen benchmark copy (text, level1_label[str]) that
scripts/evaluate.py reads. This is a one-time (or deliberate, --force'd)
snapshot: data/eval/test.csv is meant to stay fixed across model versions
so evaluation results are comparable run over run, even as
data/processed/test.csv gets regenerated by future train/test splits.

Usage (run from services/ai/):
    python scripts/prepare_eval_test_set.py
    python scripts/prepare_eval_test_set.py --force   # deliberately re-freeze

Exit codes:
    0 - wrote the frozen test set successfully
    1 - output already exists and --force was not passed
    2 - setup error (missing input file, malformed columns/labels)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

# Make the `app` package importable regardless of the caller's CWD, as long
# as this file stays at services/ai/scripts/prepare_eval_test_set.py.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.config import ID2LABEL  # noqa: E402

DEFAULT_MIN_CLASS_COUNT = 30


def parse_args() -> argparse.Namespace:
    """Parse CLI arguments for the freeze script."""
    parser = argparse.ArgumentParser(
        description=(
            "Freeze data/processed/test.csv into data/eval/test.csv with "
            "string level1_label instead of integer label, for use by "
            "scripts/evaluate.py."
        ),
    )
    parser.add_argument(
        "--input",
        default="data/processed/test.csv",
        help="Source CSV with columns text,label (int 0/1/2).",
    )
    parser.add_argument(
        "--output",
        default="data/eval/test.csv",
        help="Destination CSV with columns text,level1_label (str).",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite --output if it already exists.",
    )
    parser.add_argument(
        "--min-class-count",
        type=int,
        default=DEFAULT_MIN_CLASS_COUNT,
        help="Warn if any class has fewer than this many examples.",
    )
    return parser.parse_args()


def load_processed_test_set(path: Path) -> pd.DataFrame:
    """Load the raw processed test CSV and validate its required columns."""
    if not path.exists():
        raise FileNotFoundError(f"input test set not found at {path}")
    df = pd.read_csv(path)
    missing = {"text", "label"} - set(df.columns)
    if missing:
        raise ValueError(f"{path} is missing required columns: {sorted(missing)}")
    df = df.dropna(subset=["text", "label"]).copy()
    df["label"] = df["label"].astype(int)
    return df


def map_to_level1(df: pd.DataFrame) -> pd.DataFrame:
    """Map integer labels to level1 label strings, keeping only text/level1_label.

    Uses app.config.ID2LABEL as the single source of truth for the mapping,
    so this stays in sync with the model's own label ids automatically.
    """
    unknown_ids = set(df["label"].unique()) - set(ID2LABEL.keys())
    if unknown_ids:
        raise ValueError(
            f"unrecognized label id(s) in input: {sorted(unknown_ids)}; "
            f"expected one of {sorted(ID2LABEL.keys())}"
        )
    return pd.DataFrame(
        {
            "text": df["text"],
            "level1_label": df["label"].map(ID2LABEL),
        }
    )


def print_summary(df: pd.DataFrame, min_class_count: int) -> None:
    """Print row count and class distribution, warning on any under-sized class."""
    total = len(df)
    counts = df["level1_label"].value_counts()

    print("\n" + "=" * 60)
    print("FROZEN TEST SET SUMMARY")
    print("=" * 60)
    print(f"total rows: {total}\n")

    print("class distribution:")
    for label in ID2LABEL.values():
        n = int(counts.get(label, 0))
        pct = (n / total * 100) if total else 0.0
        print(f"  {label:<20} {n:>6}  ({pct:5.1f}%)")

    print()
    small_classes = [
        label for label in ID2LABEL.values() if counts.get(label, 0) < min_class_count
    ]
    if small_classes:
        for label in small_classes:
            n = int(counts.get(label, 0))
            print(
                f"WARNING: class '{label}' has only {n} example(s) - below the "
                f"minimum of {min_class_count} needed for a stable per-class F1 "
                f"estimate."
            )
    else:
        print(f"All classes have at least {min_class_count} examples.")


def write_output(df: pd.DataFrame, path: Path, force: bool) -> None:
    """Write the frozen eval CSV, refusing to overwrite an existing file unless forced.

    Raises FileExistsError if `path` already exists and `force` is False, so
    the frozen benchmark can't be silently clobbered by a routine re-run.
    """
    if path.exists() and not force:
        raise FileExistsError(
            f"{path} already exists. Refusing to overwrite the frozen "
            f"benchmark test set. Pass --force if you really intend to "
            f"replace it (this will change what future evaluate.py runs are "
            f"compared against)."
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(path, index=False)


def main() -> int:
    """Run the freeze end to end and return a process exit code."""
    args = parse_args()
    input_path = Path(args.input)
    output_path = Path(args.output)

    try:
        raw = load_processed_test_set(input_path)
        mapped = map_to_level1(raw)
    except (FileNotFoundError, ValueError) as exc:
        print(f"[error] {exc}", file=sys.stderr)
        return 2

    try:
        write_output(mapped, output_path, args.force)
    except FileExistsError as exc:
        print(f"[error] {exc}", file=sys.stderr)
        return 1

    print(f"Wrote {len(mapped)} rows to {output_path}")
    print_summary(mapped, args.min_class_count)
    return 0


if __name__ == "__main__":
    sys.exit(main())